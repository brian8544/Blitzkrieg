#ifndef __HASHFUNCS_H__
#define __HASHFUNCS_H__
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
#pragma ONCE
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
#include <cstddef>
#include <cstdint>
#include <functional>

struct SDefaultPtrHash
{
	std::size_t operator()(const void *pData) const noexcept { return std::hash<std::uintptr_t>{}(reinterpret_cast<std::uintptr_t>(pData)); }
};
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
struct SPtrHash
{
	template <class T>
		std::size_t operator()( const CPtr<T> &a ) const noexcept { return std::hash<std::uintptr_t>{}( reinterpret_cast<std::uintptr_t>( a.GetPtr() ) ); }
	template <class T>
		std::size_t operator()( const CObj<T> &a ) const noexcept { return std::hash<std::uintptr_t>{}( reinterpret_cast<std::uintptr_t>( a.GetPtr() ) ); }
};
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
#endif // __HASHFUNCS_H__
